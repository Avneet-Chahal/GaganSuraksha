// Generate background simulated debris population
export function generateBackgroundDebrisCatalog(count = 350): SatelliteRecord[] {
  const debrisList: SatelliteRecord[] = [...TRACKED_DEBRIS];
  const regimes: { regime: 'LEO' | 'MEO' | 'GEO'; altMin: number; altMax: number; incMin: number; incMax: number }[] = [
    { regime: 'LEO', altMin: 350, altMax: 1100, incMin: 20, incMax: 102 },
    { regime: 'LEO', altMin: 500, altMax: 900, incMin: 50, incMax: 98 },
    { regime: 'MEO', altMin: 19000, altMax: 23500, incMin: 50, incMax: 65 },
    { regime: 'GEO', altMin: 35700, altMax: 35850, incMin: 0.1, incMax: 12 },
  ];

  for (let i = 0; i < count; i++) {
    const isLeo = Math.random() < 0.82;
    const isGeo = !isLeo && Math.random() < 0.7;
    const config = isLeo ? regimes[Math.floor(Math.random() * 2)] : isGeo ? regimes[3] : regimes[2];

    const norad = 70000 + i;
    const alt = config.altMin + Math.random() * (config.altMax - config.altMin);
    const inc = config.incMin + Math.random() * (config.incMax - config.incMin);
    const raan = Math.random() * 360;
    const meanAnomaly = Math.random() * 360;
    const argPerigee = Math.random() * 360;

    const semiMajorAxisKm = 6371 + alt;
    const mu = 398600.4418;
    const nRadS = Math.sqrt(mu / Math.pow(semiMajorAxisKm, 3));
    const revsPerDay = (nRadS * 86400) / (2 * Math.PI);
    const periodMin = 1440 / revsPerDay;

    const line1 = `1 ${norad}U 98067A   26283.25000000  .00002000  00000+0  10000-3 0  9990`;
    const incStr = inc.toFixed(4).padStart(8, ' ');
    const raanStr = raan.toFixed(4).padStart(8, ' ');
    const argPStr = argPerigee.toFixed(4).padStart(8, ' ');
    const maStr = meanAnomaly.toFixed(4).padStart(8, ' ');
    const mmStr = revsPerDay.toFixed(8).padStart(11, ' ');
    const line2 = `2 ${norad} ${incStr} ${raanStr} 0015000 ${argPStr} ${maStr} ${mmStr}00001`;

    debrisList.push({
      id: `${norad}`,
      noradId: norad,
      name: `DEB-${norad} (${config.regime})`,
      intlDesignator: `1998-${(100 + (i % 800)).toString().padStart(3, '0')}A`,
      type: 'DEBRIS',
      regime: config.regime,
      isIndian: false,
      isWatchlist: false,
      ownerCountry: 'Tracked Debris',
      apogeeKm: Math.round(alt + 15),
      perigeeKm: Math.round(alt - 15),
      altitudeKm: Math.round(alt),
      inclinationDeg: Number(inc.toFixed(2)),
      periodMin: Number(periodMin.toFixed(1)),
      velocityKmS: Number(Math.sqrt(mu / semiMajorAxisKm).toFixed(2)),
      tleEpoch: '2026-10-10T06:00:00.000Z',
      tleLine1: line1,
      tleLine2: line2,
    });
  }

  return debrisList;
}

